def main():
    exps = get_experiments_list()
    print(f"Iniciando ejecución de {len(exps)} experimentos sistemáticos...")
    results = []

    for i, exp in enumerate(exps, 1):
        print(f"[{i}/{len(exps)}] Ejecutando {exp['exp_id']} ({exp['family']}): {exp['description']}...")
        r = run_single_experiment(**exp)
        results.append(r)
        print(f"     -> Val AUC: {r['val_auc']:.5f} | Val Loss: {r['val_loss']:.4f} | Val Acc: {r['val_accuracy']*100:.2f}% | Params: {r['params']} | Época: {r['best_epoch']}/{r['epochs_trained']} ({r['train_time_sec']}s)")

    df = pd.DataFrame(results)
    df = df.sort_values("val_auc", ascending=False).reset_index(drop=True)

    C.REPORTS.mkdir(exist_ok=True)
    out_csv = C.REPORTS / "experiments.csv"
    df.to_csv(out_csv, index=False)
    print(f"\n✅ Todos los {len(exps)} experimentos finalizados exitosamente.")
    print(f"Resultados guardados en: {out_csv}\n")

    print("=== TOP 5 EXPERIMENTOS POR VAL_AUC ===")
    cols_show = ["exp_id", "family", "layers", "params", "optimizer", "dropout", "batch_norm", "l2_reg", "val_auc", "val_loss", "val_accuracy", "val_f1"]
    print(df[cols_show].head(5).to_string(index=False))


if __name__ == "__main__":
    main()
